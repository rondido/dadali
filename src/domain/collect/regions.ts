// 이름 하나를 시·도 코드로. 모르는 이름은 빈 배열
export function sidoCodesOf(name: string): RegionCode[] {
  return SIDO[name.trim()] ?? [];
}

// 기관명("경기도 수원시", "울산광역시")의 첫 단어로 시·도를 찾는다. 중앙부처·재단처럼 지역을 알 수 없으면 빈 배열(전국)
export function sidoCodesOfOrg(orgName: string): RegionCode[] {
  return sidoCodesOf(orgName.trim().split(/\s+/)[0] ?? "");
}
