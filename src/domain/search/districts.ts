// 둘째 단어가 시·군·구 이름인지 ("서울특별시 마포구", "경기도 고양시 상하수도사업소")
export const DISTRICT_NAME = /[시군구]$/;

export interface OrgDistrict {
  regions: RegionCode[];
  name: string; // "마포구", "고양시"
}

// 기관명에서 시·군·구를 읽는다. 시·도나 중앙부처 기관이면 null
export function orgDistrictOf(org: string): OrgDistrict | null {
  const [first, second] = org.split(" ");
  const regions = ORG_REGIONS[first];
  if (!regions || !second || !DISTRICT_NAME.test(second)) return null;
  return { regions, name: second };
}

// 이 시·도 기관이 쓰는 기관명 첫 단어들 (DB에서 같은 규칙으로 거를 때 쓴다)
export function orgPrefixesOf(region: RegionCode): string[] {
  return Object.entries(ORG_REGIONS)
    .filter(([, regions]) => regions.includes(region))
    .map(([prefix]) => prefix);
}
